// Records the real keyboard focus order (Tab), accessible names and touch-target
// sizes for every screen state (light theme), in the installed Chrome.
// Writes ../exports/focus-audit.json and ../../docs/design/07-annex-focus-order.md.
// Exits 1 if any interactive element is smaller than 44 x 44 CSS px.
import { chromium } from "playwright-core";
import { spawn } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PORT = process.env.PORT ?? 5318;
const base = `http://127.0.0.1:${PORT}`;
async function up() { try { return (await fetch(base + "/screens/manifest.json")).ok; } catch { return false; } }
const server = spawn("npx", ["vite", "preview", "--port", String(PORT), "--host", "127.0.0.1", "--strictPort"], { cwd: ROOT, stdio: "ignore" });
for (let i = 0; i < 60 && !(await up()); i++) await new Promise((r) => setTimeout(r, 250));
const manifest = await (await fetch(base + "/screens/manifest.json")).json();
const browser = await chromium.launch({ channel: "chrome" });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce" });
const page = await ctx.newPage();
const out = [];
const small = [];
for (const s of manifest) {
  for (const st of s.states) {
    await page.goto(`${base}/screens/${s.id}/?state=${st}&theme=${s.themes[0]}&reduce=1`, { waitUntil: "networkidle" });
    await page.waitForTimeout(100);
    const order = [];
    for (let i = 0; i < 25; i++) {
      await page.keyboard.press("Tab");
      const info = await page.evaluate(() => {
        const el = document.activeElement;
        if (!el || el === document.body) return null;
        const r = el.getBoundingClientRect();
        const name = (el.getAttribute("aria-label") || (el.labels && el.labels[0]?.textContent) || el.textContent || "").trim().replace(/\s+/g, " ").slice(0, 60);
        const role = el.getAttribute("role") || el.tagName.toLowerCase();
        return { key: `${role}|${name}|${Math.round(r.x)}|${Math.round(r.y)}`, role, name, w: Math.round(r.width), h: Math.round(r.height) };
      });
      if (!info || order.some((o) => o.key === info.key)) break;
      order.push(info);
    }
    for (const o of order) if (o.role !== "main" && (o.w < 44 || o.h < 44)) small.push(`${s.id}-${st}: ${o.role} "${o.name}" ${o.w}x${o.h}`);
    out.push({ screen: `${s.id} ${s.name}`, state: st, order: order.map(({ role, name, w, h }) => ({ role, name, w, h })) });
  }
}
await browser.close();
server.kill();
fs.writeFileSync(path.resolve(ROOT, "../exports/focus-audit.json"), JSON.stringify(out, null, 2));
const md = ["# Annex: keyboard focus order and touch targets", "", "Generated by `design/prototype/scripts/focus-audit.mjs` (Tab through each screen state in Chrome, light or sun theme). Size is the focused element's box in CSS px.", ""];
for (const r of out) {
  md.push(`**${r.screen} · ${r.state}:** ` + (r.order.length ? r.order.map((o, i) => `${i + 1}. ${o.role === "main" ? "content" : `${o.role} "${o.name}"`} (${o.w}×${o.h})`).join(" → ") : "no focusable elements"));
  md.push("");
}
md.push(small.length ? `Targets under 44 px: ${small.length}\n\n${small.map((x) => "- " + x).join("\n")}` : "Targets under 44 px: none.");
fs.writeFileSync(path.resolve(ROOT, "../../docs/design/07-annex-focus-order.md"), md.join("\n") + "\n");
console.log(`Audited ${out.length} screen states. Targets under 44 px: ${small.length}`);
small.slice(0, 20).forEach((x) => console.log(" -", x));
process.exit(small.length ? 1 : 0);

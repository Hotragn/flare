// Extracts UI copy from the screens and checks the writing rules:
// buttons ≤ 3 words, banned words absent. Writes ../../docs/design/08-copy-deck.md.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(ROOT, "src/lib/screens");
const banned = /seamless|leverag|robust|empower|unlock|elevat|delve|cutting-edge|revolutioni|game-changer|harness|synergy|holistic|paradigm|next-level|supercharg|effortless|ecosystem|tapestry|testament|fast-paced|dive in/i;
const rows = []; const problems = [];
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".svelte")).sort()) {
  const src = fs.readFileSync(path.join(dir, f), "utf8");
  const id = f.match(/^([A-Z]\d+)/)[1];
  for (const m of src.matchAll(/<Button[^>]*>([^<{]+)<\/Button>/g)) {
    const t = m[1].trim(); const words = t.split(/\s+/).length;
    rows.push([id, "button", t, words]); if (words > 3) problems.push(`${id} button "${t}" has ${words} words`);
  }
  for (const m of src.matchAll(/<(h1|p)[^>]*class="[^"]*(t-display|t-title|t-sun|t-invite)[^"]*"[^>]*>([^<{]+)<\/\1>/g)) {
    const t = m[3].trim(); const words = t.split(/\s+/).length;
    rows.push([id, "message", t, words]); if (words > 12) problems.push(`${id} message "${t}" has ${words} words`);
  }
  if (banned.test(src)) problems.push(`${id} contains a banned word`);
}
const md = ["# Flare: Copy deck (extracted)", "", "Generated by `design/prototype/scripts/copy-lint.mjs` from the screen code. Limits: buttons ≤ 3 words, headline messages ≤ 12 words. Dynamic strings (names, places, times) are not listed; their templates are in handoff 04.", "", "| Screen | Kind | Text | Words |", "| --- | --- | --- | --- |", ...rows.map((r) => `| ${r[0]} | ${r[1]} | ${r[2]} | ${r[3]} |`), "", problems.length ? `Problems: ${problems.length}\n\n${problems.map((p) => "- " + p).join("\n")}` : "Problems: none."];
fs.writeFileSync(path.join(ROOT, "../../docs/design/08-copy-deck.md"), md.join("\n") + "\n");
console.log(`Copy items: ${rows.length}. Problems: ${problems.length}`);
problems.forEach((p) => console.log(" -", p));
process.exit(problems.length ? 1 : 0);

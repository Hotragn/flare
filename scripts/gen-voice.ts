// Warm-voice compass clips (ADR-0027): a fixed set of short lines, recorded once with
// ElevenLabs and shipped as static files in apps/web/static/voice/. Generated text only: the
// lines come from the copy deck and never carry a name, a place or anything a person typed, so
// nothing of anyone's reaches ElevenLabs, and the voice works offline. Existing clips are kept
// (a re-run spends no characters). Usage: node scripts/gen-voice.ts [--dry]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { applyEnvAliases } from "../packages/shared/src/env-aliases.ts";
import { loadVars } from "./telegram-lib.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "apps/web/static/voice");
const deck = JSON.parse(fs.readFileSync(path.join(ROOT, "design/prototype/src/lib/copy/deck.json"), "utf8")) as {
  strings: Record<string, { text: string }>;
};
const say = (key: string, vars: Record<string, string | number> = {}) =>
  (deck.strings[key]?.text ?? "").replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));

export const VOICE = { id: "EXAVITQu4vr4xnSDxMaL", name: "Sarah (ElevenLabs premade)" };
export const MODEL = "eleven_multilingual_v2";
/** Spoken distance buckets; lib/compass/voice.ts rounds to the nearest one. */
export const METERS = [
  ...Array.from({ length: 19 }, (_, i) => (i + 1) * 5),
  ...Array.from({ length: 18 }, (_, i) => 100 + i * 50),
];
export const KM = [1, 1.5, 2, 2.5, 3, 4, 5];
const DIRS = ["slightLeft", "slightRight", "left", "right", "behind"];

const clips: Record<string, string> = {
  ahead: say("voice.ahead"),
  close: say("voice.close"),
  flat: say("compass.holdFlat"),
  nogps: say("compass.noGps"),
  figure8: say("compass.figure8"),
  ...Object.fromEntries(DIRS.map((d) => [`dir-${d}`, `${say(`compass.dir.${d}`)}.`])),
  ...Object.fromEntries(METERS.map((m) => [`m-${m}`, `${say("voice.meters", { meters: m })},`])),
  ...Object.fromEntries(KM.map((k) => [`km-${String(k).replace(".", "_")}`, `${say("voice.km", { km: k })},`])),
};

const dry = process.argv.includes("--dry");
const vars = applyEnvAliases(loadVars());
const key = vars.ELEVENLABS_API_KEY ?? "";
if (!dry && !key) {
  console.error("ELEVENLABS_API_KEY is not set (.env)");
  process.exit(1);
}
fs.mkdirSync(OUT, { recursive: true });
let chars = 0;
let made = 0;
for (const [id, text] of Object.entries(clips)) {
  const file = path.join(OUT, `${id}.mp3`);
  if (fs.existsSync(file)) continue;
  chars += text.length;
  if (dry) continue;
  const r = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE.id}?output_format=mp3_44100_64`, {
    method: "POST",
    headers: { "xi-api-key": key, "content-type": "application/json", accept: "audio/mpeg" },
    body: JSON.stringify({
      text,
      model_id: MODEL,
      voice_settings: { stability: 0.6, similarity_boost: 0.75, speed: 0.95 },
    }),
  });
  if (!r.ok) {
    console.error(`clip ${id}: ElevenLabs ${r.status} ${(await r.text()).slice(0, 160)}`);
    process.exit(1);
  }
  fs.writeFileSync(file, Buffer.from(await r.arrayBuffer()));
  made++;
}
const manifest = {
  about: "Warm-voice compass clips, ADR-0027. Generated by scripts/gen-voice.ts from the copy deck.",
  voice: VOICE.name,
  model: MODEL,
  credit: "Voice by ElevenLabs (elevenlabs.io)",
  meters: METERS,
  km: KM,
  clips: Object.fromEntries(Object.entries(clips).map(([id, text]) => [id, { file: `/voice/${id}.mp3`, text }])),
};
fs.writeFileSync(path.join(OUT, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.info(`${dry ? "would make" : "made"} ${dry ? Object.keys(clips).length : made} clips, ${chars} characters`);
